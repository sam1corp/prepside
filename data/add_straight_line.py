# Source metadata from bracket tags when available; manual fallback for later practice section.
def src_parts(src):
    if not src: return ('Engineering Practice Sheet Solution 25','')
    # first exam label + sessions
    toks=[x.strip() for x in src.split(';')]
    exams=[]; years=[]
    for tok in toks:
        m=re.search(r'([A-Za-z]+(?:tex)?|MIST)\s*(\d{2}-\d{2})?$',tok)
        if m:
            exams.append(m.group(1));
            if m.group(2): years.append(m.group(2))
        else:
            # split e.g. BUET 06-07, 01-02
            mm=re.match(r'([A-Za-z]+(?:tex)?|MIST)\s*(.*)',tok)
            if mm:
                exams.append(mm.group(1)); years += re.findall(r'\d{2}-\d{2}',mm.group(2))
    exam='; '.join(dict.fromkeys(exams)) if exams else src
    year='; '.join(dict.fromkeys(years))
    return exam,year

