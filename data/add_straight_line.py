# OCR-derived question prompts from the scanned source. Question 39-57 are not present in the supplied PDF;
# the source jumps from 38 to 58, so they are intentionally not invented.
raw_by_page={}
for i in range(1,13):
    for side in ('L','R'):
        p=Path(f'/mnt/data/slcol_ocr/p{i:02d}-{side}.txt')
        if p.exists(): raw_by_page[(i,side)]=p.read_text(encoding='utf-8')

items=[]
for (page,side),s in raw_by_page.items():
    # Start with number at line beginning; avoid accidental numbers in solution math.
    ms=list(re.finditer(r'(?m)^(\d{1,2})[\.,)]\s*',s))
    for j,m in enumerate(ms):
        num=int(m.group(1));
        if not (1<=num<=82): continue
        st=m.end(); en=ms[j+1].start() if j+1<len(ms) else len(s)
        chunk=s[st:en]
        chunk=re.split(r'\n\s*(?:সমাধান|Solution)[:：]?',chunk,1)[0]
        chunk=' '.join(chunk.split())
        src=None
        msrc=re.search(r'\[([^\]]+)\]',chunk)
        if msrc: src=msrc.group(1)
        if src: chunk=chunk[:msrc.start()].strip()+' ['+src+']'
        if chunk and len(chunk)>20:
            items.append((num,page,side,chunk,src))

# Keep first OCR candidate for each question number, preferring the candidate containing a source tag.
by_num={}
for it in items:
    n=it[0]
    if n not in by_num or ('[' in it[3] and '[' not in by_num[n][3]): by_num[n]=it

